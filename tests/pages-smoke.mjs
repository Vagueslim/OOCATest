import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';

const url = process.argv[2];
if (!url) throw Error('Usage: node tests/pages-smoke.mjs <site-url>');
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 360, height: 800 } });
const errors = [], failedRequests = [], assets = [], checks = [];
page.on('pageerror', e => errors.push(e.message));
page.on('requestfailed', r => failedRequests.push({ url: r.url(), error: r.failure()?.errorText }));
page.on('response', r => { if (/\.(js|css|ttf)(\?|$)/.test(r.url())) assets.push({ url: r.url(), status: r.status() }); });
const button = name => page.getByRole('button', { name, exact: true });
const heading = async name => { await page.getByRole('heading', { name, exact: true }).waitFor(); };
const end = async () => { await button('จบเมื่อพร้อม').first().click(); await heading('จบรอบนี้แล้ว'); };
const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem('ooca-demo:saved-quotes:v1') || '{"entries":[]}').entries);
await mkdir('evidence/live', { recursive: true });
try {
  const response = await page.goto(url, { waitUntil: 'networkidle' });
  assert.equal(response.status(), 200);
  await heading('Peek a word!');
  await page.evaluate(() => document.fonts.ready);
  assert(await page.evaluate(() => document.fonts.check('16px Prompt')));
  checks.push('Page and Prompt font loaded');
  await button('เริ่ม').click();
  await page.screenshot({ path: 'evidence/live/mobile-discover.png', fullPage: true });
  await button('จบได้เลย').click(); await heading('จบรอบนี้แล้ว');
  assert.equal((await stored()).length, 0); checks.push('End before selection');
  await button('เริ่มรอบใหม่').click(); await button('เลือกข้อความนี้').click();
  await page.screenshot({ path: 'evidence/live/mobile-reflect.png', fullPage: true });
  await end(); assert.equal((await stored()).length, 0); checks.push('Select, skip all optional actions, end');
  await button('เริ่มรอบใหม่').click(); await button('เลือกข้อความนี้').click();
  await page.getByRole('radio', { name: 'ตนเอง', exact: true }).check();
  await button('เก็บข้อความไว้').click();
  await page.getByRole('textbox').fill('PRIVATE LIVE TEST');
  await end(); assert.equal((await stored()).length, 1);
  assert(!JSON.stringify(await stored()).includes('PRIVATE'));
  await button('ดูข้อความที่เก็บไว้').click(); await page.locator('summary').first().click();
  await page.getByText('นึกถึง: ตนเอง', { exact: true }).waitFor();
  await page.reload({ waitUntil: 'networkidle' }); await heading('Peek a word!');
  assert.equal((await stored()).length, 1); checks.push('Save, history, draft privacy and reload at repository URL');
  await button('เริ่ม').click(); await button('วันนี้ยังไม่เลือก').click();
  await button('รับกอด').click(); await page.getByText('ไว้ค่อยกลับมาเมื่อพร้อม').waitFor();
  await button('จบได้เลย').click(); checks.push('No selection, hug, end');
  await button('เริ่มรอบใหม่').click(); await button('เลือกข้อความนี้').click();
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new DOMException('test blocked', 'QuotaExceededError'); }; });
  await button('เก็บข้อความไว้').click();
  await page.getByText('ตอนนี้เก็บข้อความในเบราว์เซอร์นี้ไม่ได้', { exact: true }).waitFor();
  await end(); assert.equal(await page.getByText('เก็บข้อความไว้แล้ว', { exact: true }).count(), 0);
  await page.screenshot({ path: 'evidence/live/mobile-done.png', fullPage: true });
  assert.equal((await stored()).length, 1); checks.push('Failed save keeps earlier data and permits end without false success');
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.equal(new URL(page.url()).pathname, new URL(url).pathname);
  assert.equal(errors.length, 0); assert.equal(failedRequests.length, 0);
  assert(assets.some(a => a.url.includes('/OOCATest/assets/')));
  assert(assets.some(a => a.url.includes('/OOCATest/fonts/Prompt-Regular.ttf')));
  assert(assets.every(a => [200, 304].includes(a.status))); checks.push('Repository asset paths, no runtime/network errors, no mobile horizontal overflow');
  const result = { url: page.url(), checkedAt: new Date().toISOString(), viewport: '360x800 Chromium', checks, errors, failedRequests, assets, passed: true };
  await writeFile('evidence/live/results.json', JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
} finally { await browser.close(); }

